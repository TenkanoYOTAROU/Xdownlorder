local last = nil
local function try()
  local ok, st = pcall(function() return City.getStorage() end)
  if not ok or type(st) ~= "table" or st == last then return end
  last = st
  if st.cliffwall_data ~= nil then
    log("data already in this city's storage")
    return
  end
  local seed = "?"
  pcall(function() seed = tostring(City.getSeed()) end)
  if string.sub(seed, -4) ~= ".png" then
    log("seed " .. seed .. " is not a .png heightmap city : not written")
    return
  end
  st.cliffwall_data = { version = 1, mapSeed = seed, n = 64, write = true, rows = ROWS, edges = EDGES }
  log("WRITTEN cliff data to storage: seed=" .. seed .. " rows=" .. #ROWS)
  pcall(function() Debug.toast("cliff data: written") end)
end

function script:enterCity() try() end
function script:update() try() end
